/**
 * Concurrent Dual-Slider Animator
 */
function animateDualSliders(fromFacts, toFacts, fromK, toK, durationMs, onUpdate) {
  if (state.tourRaf) {
    cancelAnimationFrame(state.tourRaf);
    state.tourRaf = null;
  }

  const startT = performance.now();
  const sliderFacts = document.getElementById("slider-facts");
  const displayFacts = document.getElementById("val-facts");
  const sliderK = document.getElementById("slider-k");
  const displayK = document.getElementById("val-k");

  function step(now) {
    const progress = Math.min(1, (now - startT) / durationMs);
    const curFacts = Math.round(fromFacts + (toFacts - fromFacts) * progress);
    const curK = Math.round(fromK + (toK - fromK) * progress);

    if (sliderFacts) sliderFacts.value = curFacts;
    if (displayFacts) displayFacts.textContent = `${curFacts} / ${state.facts.length}`;

    if (sliderK) sliderK.value = curK;
    if (displayK) displayK.textContent = `k = ${curK} (${((curK / N) * 100).toFixed(1)}%)`;

    onUpdate(curFacts, curK);

    if (progress < 1) {
      state.tourRaf = requestAnimationFrame(step);
    } else {
      state.tourRaf = null;
    }
  }
  state.tourRaf = requestAnimationFrame(step);
}

/**
 * Single-Slider Animator for Step 3
 */
function animateSingleSlider(startVal, endVal, durationMs, sliderId, displayId, onUpdate) {
  if (state.tourRaf) {
    cancelAnimationFrame(state.tourRaf);
    state.tourRaf = null;
  }

  const startT = performance.now();
  const sliderElem = document.getElementById(sliderId);
  const displayElem = document.getElementById(displayId);

  function step(now) {
    const progress = Math.min(1, (now - startT) / durationMs);
    const currentVal = Math.round(startVal + (endVal - startVal) * progress);

    if (sliderElem) sliderElem.value = currentVal;
    if (displayElem) {
      if (sliderId === "slider-k") {
        displayElem.textContent = `k = ${currentVal} (${((currentVal / N) * 100).toFixed(1)}%)`;
      } else {
        displayElem.textContent = `${currentVal} / ${state.facts.length}`;
      }
    }
    onUpdate(currentVal);

    if (progress < 1) {
      state.tourRaf = requestAnimationFrame(step);
    } else {
      state.tourRaf = null;
    }
  }
  state.tourRaf = requestAnimationFrame(step);
}

