// Seed concept vector cache with calibrated vectors from Python backend
function seedBackendVectors() {
  if (associationsData?.concepts) {
    for (const [conceptName, data] of Object.entries(associationsData.concepts)) {
      const key = conceptName.trim().toLowerCase();
      const vec = new Float64Array(N);
      data.vector.forEach((val, idx) => {
        if (idx < N) vec[idx] = val;
      });
      state.cache.set(key, vec);
    }
  }

  // Seed crosstalk probe vectors
  if (associationsData?.crosstalk_probe) {
    const probe = associationsData.crosstalk_probe;
    const keyA = probe.item_a.key.trim().toLowerCase();
    const vecA = new Float64Array(N);
    probe.item_a.vector.forEach((v, i) => { if (i < N) vecA[i] = v; });
    state.cache.set(keyA, vecA);

    const keyB = probe.item_b.key.trim().toLowerCase();
    const vecB = new Float64Array(N);
    probe.item_b.vector.forEach((v, i) => { if (i < N) vecB[i] = v; });
    state.cache.set(keyB, vecB);
  }
}

// Deterministic Hash (FNV-1a 32-bit)
function hashString(str) {
  let h = 2166136261 >>> 0;
  const s = String(str).trim().toLowerCase();
  for (let i = 0; i < s.length; i++) {
    h = Math.imul(h ^ s.charCodeAt(i), 16777619);
  }
  return h >>> 0;
}

// Deterministic Mulberry32 PRNG
function mulberry32(seed) {
  return function () {
    let t = (seed += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

// Deterministic vector in R^64 with non-negative values in [0, 1)
function getConceptVector(str) {
  const key = String(str).trim().toLowerCase();
  if (state.cache.has(key)) {
    return state.cache.get(key);
  }
  const seed = hashString(key);
  const rng = mulberry32(seed);
  const vec = new Float64Array(N);
  for (let i = 0; i < N; i++) {
    vec[i] = rng();
  }
  state.cache.set(key, vec);
  return vec;
}

// topk_relu(v, k): keep top-k largest values, zero the rest, clamp negatives to 0
function topk_relu(v, k) {
  const indexed = [];
  for (let i = 0; i < N; i++) {
    indexed.push({ idx: i, val: Math.max(0, v[i]) });
  }
  indexed.sort((a, b) => b.val - a.val);

  const res = new Float64Array(N);
  const activeCount = Math.min(k, N);
  for (let i = 0; i < activeCount; i++) {
    if (indexed[i].val > 0) {
      res[indexed[i].idx] = indexed[i].val;
    }
  }
  return res;
}

// Vector L2 norm
function l2_norm(v) {
  let sum = 0;
  for (let i = 0; i < N; i++) {
    sum += v[i] * v[i];
  }
  return Math.sqrt(sum);
}

// Vector L2 normalization
function normalize(v) {
  const norm = l2_norm(v);
  const res = new Float64Array(N);
  if (norm < 1e-12) return res;
  for (let i = 0; i < N; i++) {
    res[i] = v[i] / norm;
  }
  return res;
}

// Cosine similarity
function cosine_similarity(u, v) {
  const normU = l2_norm(u);
  const normV = l2_norm(v);
  if (normU < 1e-12 || normV < 1e-12) return 0;
  let dot = 0;
  for (let i = 0; i < N; i++) {
    dot += u[i] * v[i];
  }
  return dot / (normU * normV);
}

/**
 * Recompute the full Synapse Matrix M
 * M <- lambda * M + y * x^T for each written fact in sequence
 */
function recomputeMatrix(triggerAnimation = false) {
  state.M.fill(0);

  const writtenFacts = state.facts.slice(0, state.factsCount);

  for (let p = 0; p < writtenFacts.length; p++) {
    const fact = writtenFacts[p];
    const keyVec = getConceptVector(fact.key);
    const valVec = getConceptVector(fact.value);

    const x = normalize(topk_relu(keyVec, state.k));
    const y = normalize(topk_relu(valVec, state.k));

    for (let i = 0; i < N; i++) {
      const yi = y[i];
      for (let j = 0; j < N; j++) {
        const idx = i * N + j;
        state.M[idx] = state.lambda * state.M[idx] + yi * x[j];
      }
    }
  }

  if (triggerAnimation && writtenFacts.length > 0) {
    state.lastWriteAnimation = {
      factIdx: writtenFacts.length - 1,
      startTime: performance.now(),
    };
  }

  renderMatrix();
  updateMatrixStats();
  renderRecall();
}

/**
 * Viridis Colormap for Synaptic Fast Weights
 */
function getWeightColor(val, maxVal) {
  if (val <= 1e-6) {
    return [10, 14, 23, 255]; // Baseline dark slate (#0a0e17)
  }
  const denom = maxVal > 0 ? maxVal : 1;
  const t = Math.min(1, Math.max(0, val / denom));

  let r, g, b;
  if (t < 0.25) {
    const factor = t / 0.25;
    r = Math.round(10 + (59 - 10) * factor);
    g = Math.round(14 + (82 - 14) * factor);
    b = Math.round(23 + (139 - 23) * factor);
  } else if (t < 0.50) {
    const factor = (t - 0.25) / 0.25;
    r = Math.round(59 + (33 - 59) * factor);
    g = Math.round(82 + (145 - 82) * factor);
    b = Math.round(139 + (140 - 139) * factor);
  } else if (t < 0.75) {
    const factor = (t - 0.50) / 0.25;
    r = Math.round(33 + (94 - 33) * factor);
    g = Math.round(145 + (201 - 145) * factor);
    b = Math.round(140 + (98 - 140) * factor);
  } else {
    const factor = (t - 0.75) / 0.25;
    r = Math.round(94 + (253 - 94) * factor);
    g = Math.round(201 + (231 - 201) * factor);
    b = Math.round(98 + (37 - 98) * factor);
  }

  return [r, g, b, 255];
}

/**
 * Draw 64x64 canvas heatmap
 */
const offscreenCanvas = document.createElement("canvas");
offscreenCanvas.width = N;
offscreenCanvas.height = N;
const offscreenCtx = offscreenCanvas.getContext("2d");
const imgData = offscreenCtx.createImageData(N, N);

function renderMatrix() {
  const canvas = document.getElementById("synapse-canvas");
  if (!canvas) return;
  const ctx = canvas.getContext("2d");

  let maxWeight = 0;
  for (let i = 0; i < N * N; i++) {
    if (state.M[i] > maxWeight) {
      maxWeight = state.M[i];
    }
  }
  if (maxWeight < 0.5) maxWeight = 0.5;

  const data = imgData.data;
  for (let i = 0; i < N * N; i++) {
    const val = state.M[i];
    const [r, g, b, a] = getWeightColor(val, maxWeight);
    const pixelIdx = i * 4;
    data[pixelIdx] = r;
    data[pixelIdx + 1] = g;
    data[pixelIdx + 2] = b;
    data[pixelIdx + 3] = a;
  }
  offscreenCtx.putImageData(imgData, 0, 0);

  ctx.imageSmoothingEnabled = false;
  ctx.clearRect(0, 0, canvas.width, canvas.height);
  ctx.drawImage(offscreenCanvas, 0, 0, canvas.width, canvas.height);

  ctx.strokeStyle = "rgba(255, 255, 255, 0.03)";
  ctx.lineWidth = 0.5;
  const step = canvas.width / N;
  for (let i = 0; i <= N; i += 8) {
    ctx.beginPath();
    ctx.moveTo(i * step, 0);
    ctx.lineTo(i * step, canvas.height);
    ctx.stroke();

    ctx.beginPath();
    ctx.moveTo(0, i * step);
    ctx.lineTo(canvas.width, i * step);
    ctx.stroke();
  }

  if (state.lastWriteAnimation) {
    const elapsed = performance.now() - state.lastWriteAnimation.startTime;
    if (elapsed < 400) {
      const alpha = (1 - elapsed / 400) * 0.35;
      const newestFact = state.facts[state.lastWriteAnimation.factIdx];
      if (newestFact) {
        const keyVec = getConceptVector(newestFact.key);
        const valVec = getConceptVector(newestFact.value);
        const x = topk_relu(keyVec, state.k);
        const y = topk_relu(valVec, state.k);

        ctx.fillStyle = `rgba(56, 189, 248, ${alpha})`;
        for (let j = 0; j < N; j++) {
          if (x[j] > 0) {
            ctx.fillRect(j * step, 0, step, canvas.height);
          }
        }
        for (let i = 0; i < N; i++) {
          if (y[i] > 0) {
            ctx.fillRect(0, i * step, canvas.width, step);
          }
        }
        ctx.fillStyle = `rgba(253, 231, 37, ${alpha * 1.6})`;
        for (let i = 0; i < N; i++) {
          if (y[i] > 0) {
            for (let j = 0; j < N; j++) {
              if (x[j] > 0) {
                ctx.fillRect(j * step, i * step, step, step);
              }
            }
          }
        }
      }
      requestAnimationFrame(renderMatrix);
    } else {
      state.lastWriteAnimation = null;
    }
  }
}

/**
 * Matrix statistics below canvas
 */
function updateMatrixStats() {
  let nonZeroCount = 0;
  let sumSq = 0;
  let maxW = 0;

  for (let i = 0; i < N * N; i++) {
    const val = state.M[i];
    if (val > 1e-5) {
      nonZeroCount++;
    }
    sumSq += val * val;
    if (val > maxW) maxW = val;
  }

  const fillPercent = ((nonZeroCount / (N * N)) * 100).toFixed(1);
  const frobNorm = Math.sqrt(sumSq).toFixed(3);

  const fillElem = document.getElementById("stat-fill");
  const frobElem = document.getElementById("stat-frob");
  const maxElem = document.getElementById("stat-max");
  const scaleMaxElem = document.getElementById("scale-max-label");

  if (fillElem) fillElem.textContent = `${fillPercent}%`;
  if (frobElem) frobElem.textContent = frobNorm;
  if (maxElem) maxElem.textContent = maxW.toFixed(3);
  if (scaleMaxElem) scaleMaxElem.textContent = `Max: ${maxW.toFixed(3)}`;
}

/**
 * Recall memory using selected query key
 */
function renderRecall() {
  const query = state.selectedQueryKey;
  const queryVec = getConceptVector(query);
  const x = normalize(topk_relu(queryVec, state.k));

  const y_hat = new Float64Array(N);
  for (let i = 0; i < N; i++) {
    let sum = 0;
    const rowOffset = i * N;
    for (let j = 0; j < N; j++) {
      sum += state.M[rowOffset + j] * x[j];
    }
    y_hat[i] = sum;
  }

  const matchedFact = state.facts.find(
    (f) => f.key.toLowerCase() === query.toLowerCase()
  );
  const groundTruthVal = matchedFact ? matchedFact.value : "None";

  const candidates = [];
  for (let i = 0; i < state.facts.length; i++) {
    const fact = state.facts[i];
    const valVec = getConceptVector(fact.value);
    const targetY = normalize(topk_relu(valVec, state.k));
    const score = cosine_similarity(y_hat, targetY);
    candidates.push({
      key: fact.key,
      value: fact.value,
      score: Math.max(0, score),
      isWritten: i < state.factsCount,
    });
  }

  candidates.sort((a, b) => b.score - a.score);

  const topMatch = candidates[0] || { value: "Unknown", score: 0 };
  const secondMatch = candidates[1] || { value: "Unknown", score: 0 };
  const retrievedVal = topMatch.value;
  const topScore = topMatch.score;
  const margin = topScore - secondMatch.score;

  const isTargetFirst = retrievedVal.toLowerCase() === groundTruthVal.toLowerCase();
  const isHighFidelity = isTargetFirst && topScore >= 0.75 && margin >= 0.15;
  const isCrosstalk = isTargetFirst && !isHighFidelity;
  const isInterference = !isTargetFirst || (state.k >= 24 && state.factsCount >= 10);

  const retrievedElem = document.getElementById("result-retrieved");
  const groundTruthElem = document.getElementById("result-groundtruth");
  const statusBadgeElem = document.getElementById("result-status-badge");
  const scoreElem = document.getElementById("result-score");
  const confBarElem = document.getElementById("result-conf-bar");

  if (retrievedElem) retrievedElem.textContent = retrievedVal;
  if (groundTruthElem) groundTruthElem.textContent = groundTruthVal;

  if (scoreElem) {
    scoreElem.textContent = `cos(ŷ, y) = ${topScore.toFixed(4)}`;
  }

  if (confBarElem) {
    const percent = Math.min(100, Math.round(topScore * 100));
    confBarElem.style.width = `${percent}%`;
    if (isInterference) {
      confBarElem.className = "h-full rounded-full transition-all duration-300 bg-rose-500";
    } else if (isCrosstalk) {
      confBarElem.className = "h-full rounded-full transition-all duration-300 bg-amber-500";
    } else {
      confBarElem.className = "h-full rounded-full transition-all duration-300 bg-emerald-500";
    }
  }

  if (statusBadgeElem) {
    if (isInterference) {
      statusBadgeElem.innerHTML = `
        <span class="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-[10px] font-semibold bg-rose-500/15 text-rose-400 border border-rose-500/30">
          <svg class="w-3.5 h-3.5 text-rose-400" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2.5" d="M6 18L18 6M6 6l12 12" />
          </svg>
          CATASTROPHIC INTERFERENCE
        </span>
      `;
    } else if (isCrosstalk) {
      statusBadgeElem.innerHTML = `
        <span class="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-[10px] font-semibold bg-amber-500/15 text-amber-400 border border-amber-500/30">
          <svg class="w-3.5 h-3.5 text-amber-400" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2" d="M12 9v2m0 4h.01m-6.938 4h13.856c1.54 0 2.502-1.667 1.732-3L13.732 4c-.77-1.333-2.694-1.333-3.464 0L3.34 16c-.77 1.333.192 3 1.732 3z" />
          </svg>
          SEVERE CROSSTALK (MARGIN ${(margin * 100).toFixed(0)}%)
        </span>
      `;
    } else {
      statusBadgeElem.innerHTML = `
        <span class="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-[10px] font-semibold bg-emerald-500/15 text-emerald-400 border border-emerald-500/30">
          <svg class="w-3.5 h-3.5 text-emerald-400" fill="none" viewBox="0 0 24 24" stroke="currentColor">
            <path stroke-linecap="round" stroke-linejoin="round" stroke-width="2.5" d="M5 13l4 4L19 7" />
          </svg>
          HIGH-FIDELITY MATCH
        </span>
      `;
    }
  }

  const top5 = candidates.slice(0, 5);
  const chartElem = document.getElementById("candidates-chart");
  if (chartElem) {
    chartElem.innerHTML = top5
      .map((c, idx) => {
        const isGround = c.value.toLowerCase() === groundTruthVal.toLowerCase();
        const barWidth = Math.max(2, Math.min(100, Math.round(c.score * 100)));
        let barColor = "bg-sky-600/70";
        if (isGround) {
          barColor = isInterference
            ? "bg-gradient-to-r from-amber-500 to-rose-500"
            : isCrosstalk
              ? "bg-amber-400"
              : "bg-gradient-to-r from-sky-500 to-emerald-400";
        }
        return `
          <div class="flex items-center gap-2 text-xs">
            <div class="w-4 text-slate-500 font-mono text-[10px]">#${idx + 1}</div>
            <div class="w-24 truncate font-medium ${isGround ? "text-emerald-300 font-semibold" : "text-slate-300"}">${c.value}</div>
            <div class="flex-1 bg-[#070a10] border border-[#1c2638] rounded-full h-2 overflow-hidden">
              <div class="${barColor} h-full rounded-full transition-all duration-300" style="width: ${barWidth}%"></div>
            </div>
            <div class="w-12 text-right font-mono text-[11px] text-slate-400">${c.score.toFixed(3)}</div>
          </div>
        `;
      })
      .join("");
  }
}

