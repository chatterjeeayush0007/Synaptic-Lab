/**
 * Autoplay Cycle Stepper
 * Automatically shifts sliders to prove biological memory dynamics while user tests queries
 */
function stepAutoplay() {
  if (!state.autoplayActive || state.tourActive) return;

  const config = AUTOPLAY_CYCLE[state.autoplayStepIndex];
  state.autoplayStepIndex = (state.autoplayStepIndex + 1) % AUTOPLAY_CYCLE.length;

  state.factsCount = config.facts;
  state.k = config.k;
  state.lambda = config.lambda;
  state.contextTokens = config.context;

  // Synchronize DOM Sliders & Text Displays
  const sliderFacts = document.getElementById("slider-facts");
  const displayFacts = document.getElementById("val-facts");
  const sliderK = document.getElementById("slider-k");
  const displayK = document.getElementById("val-k");
  const sliderLambda = document.getElementById("slider-lambda");
  const displayLambda = document.getElementById("val-lambda");
  const sliderContext = document.getElementById("slider-context");

  if (sliderFacts) sliderFacts.value = config.facts;
  if (displayFacts) displayFacts.textContent = `${config.facts} / ${state.facts.length}`;

  if (sliderK) sliderK.value = config.k;
  if (displayK) displayK.textContent = `k = ${config.k} (${((config.k / N) * 100).toFixed(1)}%)`;

  if (sliderLambda) sliderLambda.value = config.lambda.toFixed(2);
  if (displayLambda) displayLambda.textContent = `λ = ${config.lambda.toFixed(2)}`;

  if (sliderContext) sliderContext.value = config.context;

  renderFactList();
  updateQueryDropdown();
  updateFormulaDisplay();
  updateMemoryMeter();

  // Pulse new matrix state with rank-1 flash
  recomputeMatrix(true);
}

function startAutoplay() {
  if (state.autoplayIntervalId) {
    clearInterval(state.autoplayIntervalId);
  }
  state.autoplayActive = true;
  updateAutoplayButtonUI();
  state.autoplayIntervalId = setInterval(stepAutoplay, 2400);
}

function stopAutoplay() {
  state.autoplayActive = false;
  if (state.autoplayIntervalId) {
    clearInterval(state.autoplayIntervalId);
    state.autoplayIntervalId = null;
  }
  updateAutoplayButtonUI();
}

function toggleAutoplay() {
  if (state.autoplayActive) {
    stopAutoplay();
  } else {
    // If walkthrough is running, close it so autoplay can take the canvas
    if (state.tourActive) {
      endGuidedTour();
    } else {
      startAutoplay();
    }
  }
}

